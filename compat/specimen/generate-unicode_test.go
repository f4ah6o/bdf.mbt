//go:build ignore

// Copy into the upstream converter/font package and run TestCodexUnicodeTables.
package font

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
	"unicode"
)

func TestCodexUnicodeTables(t *testing.T) {
	root := os.Getenv("BDF_FIXTURE_ROOT")
	if root == "" {
		t.Fatal("BDF_FIXTURE_ROOT required")
	}
	if unicode.Version != "17.0.0" {
		t.Fatal("expected Go Unicode 17.0.0, got ", unicode.Version)
	}
	var b strings.Builder
	b.WriteString("///|\n// Generated by compat/specimen/generate-unicode_test.go from upstream Unicode 17.\nlet specimen_blocks : Array[UnicodeBlock] = [\n")
	for _, block := range blocks {
		count := 0
		for r := block.first; r <= block.last; r++ {
			if assigned(r) {
				count++
			}
		}
		fmt.Fprintf(&b, "  { first: 0x%x, last: 0x%x, name: %q, assigned: %d },\n", block.first, block.last, block.name, count)
	}
	b.WriteString("]\n\n///|\n// Inclusive ranges of Unicode graphic non-space, non-Mn characters.\nlet specimen_graphic_ranges : Array[(Int32, Int32)] = [\n")
	start := -1
	for r := 0; r <= unicode.MaxRune+1; r++ {
		yes := r <= unicode.MaxRune && unicode.IsGraphic(rune(r)) && !unicode.IsSpace(rune(r)) && !unicode.Is(unicode.Mn, rune(r))
		if yes && start < 0 {
			start = r
		}
		if !yes && start >= 0 {
			fmt.Fprintf(&b, "  (0x%x, 0x%x),\n", start, r-1)
			start = -1
		}
	}
	b.WriteString("]\n")
	if err := os.WriteFile(filepath.Join(root, "convert/font/unicode_generated.mbt"), []byte(b.String()), 0644); err != nil {
		t.Fatal(err)
	}
}
