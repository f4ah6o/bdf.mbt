//go:build ignore

// Copy into upstream converter/font and run TestCodexSimpleFold.
package font

import (
	"fmt"
	"os"
	"path/filepath"
	"testing"
	"unicode"
)

func TestCodexSimpleFold(t *testing.T) {
	root := os.Getenv("BDF_FIXTURE_ROOT")
	if root == "" {
		t.Fatal("BDF_FIXTURE_ROOT required")
	}
	if unicode.Version != "17.0.0" {
		t.Fatalf("Unicode 17 required; got %s", unicode.Version)
	}
	out := "///|\n// Generated by compat/specimen/generate-fold_test.go from Go Unicode 17.\nlet specimen_simple_folds : Array[(Int32, Int32)] = [\n"
	for r := rune(0); r <= unicode.MaxRune; r++ {
		next := unicode.SimpleFold(r)
		if next == r {
			continue
		}
		least := r
		for next != r {
			if next < least {
				least = next
			}
			next = unicode.SimpleFold(next)
		}
		if least != r {
			out += fmt.Sprintf("  (0x%x, 0x%x),\n", r, least)
		}
	}
	out += "]\n"
	if err := os.WriteFile(filepath.Join(root, "convert/font/simple_fold_generated.mbt"), []byte(out), 0644); err != nil {
		t.Fatal(err)
	}
}
