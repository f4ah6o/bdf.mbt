// Generate MoonBit search tests from the upstream implementation.
import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { BdfDocument, BufferSource, TextSearch, normalizeQuery } from '@bdfkit/core';

const target = new URL('../../core/search_generated_test.mbt', import.meta.url);
const run = (text, sep = 0, a = 0, b = 0, ordinal = 0) => ({a,b,ordinal,sep,text});
const cases = [
  {name:'latin accents', runs:[run('un cafe\u0301 noir CAFÉ')], queries:['café','CAFE\u0301','cafe','É','noir']},
  {name:'kana width', runs:[run('ｶﾞｲﾄﾞ カタカナ ㌔ ﾊﾟ')], queries:['ガイド','がいど','い','ド','ト','ろ','パ']},
  {name:'hangul and marks', runs:[run('𝒜 a\u0301\u0323b x\u1100\u1161\u11a8y')], queries:['a\u0323\u0301','a','각','b','x각y']},
  {name:'case and formula', runs:[run('ＡＢＣ Ⅸ b^2−4ac İ Σς 𐐀')], queries:['abc','ix','B^2-4AC','i\u0307','σ','ς','𐐨']},
  {name:'case sensitive', sensitive:true, runs:[run('ABC Abc ａｂｃ カナ')], queries:['ABC','abc','カナ','かな']},
  {name:'boundaries', runs:[run('Hello',2,0,1,9),run('World',1,0,1,10),run('wide',0,0,2,0),run('next',2,1,0,3)], queries:['hello world','WORLDWIDE','wide next','wide\u0000next','next',' ','','o']},
  {name:'split normalization', runs:[run('e'),run('\u0301x',0)], queries:['é','e\u0301x','e','\u0301','x']},
  {name:'overlap and context', runs:[run('banana'),run('BANANA',2,2,3,4)], queries:['ana','a','nan','banana'],context:2,limit:4},
  {name:'query whitespace', runs:[run('a b c\u0085d')], queries:['a\t\n b','b\u00a0c','c\u0085d','\ufeff']},
  {name:'empty and other separator', runs:[run(''),run('a',7),run('',1),run('b',1)], queries:['a b','a  b',' ','b']},
  {name:'limit zero', runs:[run('aaaa')], queries:['a'],limit:0},
  {name:'negative context', runs:[run('abcdefghijk')], queries:['a','d','k'],context:-2},
];
const bytes = readFileSync(new URL('../interactive/fixture.bdf', import.meta.url));
const document = await BdfDocument.open(new BufferSource(bytes));
cases.push({
  name:'real BDF page and layer index',
  runs:await document.textIndex(document.manifest.views[0]),
  queries:['document example','hello world','second line','annotation','second page','header value','chart','price','42'],
});
const normal = ['ＡＢＣ ｶﾀｶﾅ Ⅸ','cafe\u0301','ｶﾞｲﾄﾞ','\u304b\u3099','\u1100\u1161\u11a8','a\u0301\u0323','10⁻³','İΣ𐐀'];
const q = s => JSON.stringify(s).replace(/\\u0000/g, '\\u{0}');
const index = r => `{ a: ${r.a}, b: ${r.b}, ordinal: ${r.ordinal}, separator: ${r.sep}, text: ${q(r.text)} }`;
const segment = s => `{ run: ${s.run}, a: ${s.a}, b: ${s.b}, ordinal: ${s.ordinal}, start: ${s.start}, end: ${s.end} }`;
const hit = h => `{ segments: [${h.segments.map(segment).join(', ')}], text: ${q(h.text)}, context: ${q(h.context)} }`;
let result = '///|\n// Generated by compat/search/generate.mjs from @bdfkit/core.\n';
result += 'test "search query normalization matches upstream" {\n';
for (const s of normal) for (const sensitive of [false,true]) result += `  assert_eq(@core.normalize_query(${q(s)}, case_sensitive=${sensitive}), ${q(normalizeQuery(s,sensitive))})\n`;
result += '}\n';
for (const c of cases) {
  const search = new TextSearch(c.runs, c.sensitive ?? false);
  const opts = {limit:c.limit ?? 1000, context:c.context ?? 40};
  result += `\n///|\ntest ${q('upstream search: '+c.name)} {\n`;
  result += `  let runs : Array[@core.IndexRun] = [${c.runs.map(index).join(', ')}]\n`;
  result += `  let search = @core.TextSearch::new(runs, case_sensitive=${c.sensitive ?? false})\n`;
  result += `  assert_eq(search.text(), ${q(search.text)})\n`;
  for (const query of c.queries) {
    const hits = search.search(query,opts);
    result += `  {\n    let expected : Array[@core.SearchHit] = [${hits.map(hit).join(', ')}]\n`;
    result += `    assert_eq(search.search(${q(query)}, limit=${opts.limit}, context=${opts.context}), expected)\n  }\n`;
  }
  result += '}\n';
}
const fmt = spawnSync('moonfmt', ['-'], {input:result, encoding:'utf8'});
if (fmt.error || fmt.status !== 0) throw fmt.error ?? new Error(fmt.stderr);
result = fmt.stdout;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== result) throw new Error('MoonBit search fixture differs from upstream; run node compat/search/generate.mjs');
  console.log('MoonBit search fixtures match upstream results.');
} else {
  writeFileSync(target, result);
}
