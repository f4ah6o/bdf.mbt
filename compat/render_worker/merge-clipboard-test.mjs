import assert from 'node:assert/strict';
import { createReadStream, existsSync } from 'node:fs';
import { createServer } from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

// Deterministic regression for sheetClipboard merged cells whose span is
// wider than one tile. The merge fixture (compat/sheet/merge.bdf) anchors an
// A1:Z1 merge and a B3:B40 merge in tile (0,0) while the sheet has 8x7 tiles,
// so selections more than one tile away from the anchor must still see the
// merged text, clipped by @render.cell_clipboard. Every expectation runs
// against buffer and split sources, including their password-encrypted
// mirrors (compat/sheet/merge-encrypted.bdf, generated by merge-generate.go).
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const localBuilds = [
  '_build/js/debug/build/browser/browser.js',
  '_build/js/debug/build/render_worker/render_worker.js',
];
for (const build of localBuilds) {
  if (!existsSync(path.join(root, build))) {
    throw new Error('missing local build ' + build + '; run: moon build browser render_worker --target js');
  }
}

// Only the merge fixture, its split mirror and the local builds are readable.
const allowed = [
  '/compat/sheet/merge.bdf',
  '/compat/sheet/merge-split/',
  '/compat/sheet/merge-encrypted.bdf',
  '/compat/sheet/merge-encrypted-split/',
  '/_build/js/debug/build/browser/',
  '/_build/js/debug/build/render_worker/',
];
const server = createServer((request, response) => {
  let pathname;
  try { pathname = decodeURIComponent(new URL(request.url, 'http://localhost').pathname); }
  catch { response.writeHead(400).end(); return; }
  if (pathname === '/' || pathname === '/merge-test.html') {
    response.setHeader('Content-Type', 'text/html; charset=utf-8');
    response.end('<!doctype html><meta charset="utf-8"><title>merge sheetClipboard</title>');
    return;
  }
  const resolved = path.resolve(root, '.' + pathname);
  if (!allowed.some((prefix) => resolved.startsWith(path.resolve(root, '.' + prefix) + path.sep) || resolved === path.join(root, prefix))) {
    response.writeHead(403).end();
    return;
  }
  const stream = createReadStream(resolved);
  stream.once('error', () => { if (!response.headersSent) response.writeHead(404); response.end(); });
  response.setHeader('Content-Type', pathname.endsWith('.js') ? 'text/javascript' : 'application/octet-stream');
  stream.pipe(response);
});
await new Promise((resolve, reject) => {
  server.once('error', reject);
  server.listen(0, '127.0.0.1', resolve);
});
const base = 'http://127.0.0.1:' + server.address().port;

// Sheet axes: columns A,B,D..Z are visible (C is a hidden run), rows 1..43
// are visible, so the merged span clips to the visible columns it covers.
const meta = '<meta charset="utf-8"><table>';
const cases = [
  // The anchor cell itself.
  ['anchor', { row0: 0, col0: 0, row1: 0, col1: 0 }, {
    text: 'Long merged',
    html: meta + '<tr><td>Long merged</td></tr></table>',
  }],
  // A single far cell inside the A1:Z1 merge, seven tiles from its anchor.
  ['merge-far', { row0: 0, col0: 24, row1: 0, col1: 24 }, {
    text: 'Long merged',
    html: meta + '<tr><td>Long merged</td></tr></table>',
  }],
  // A band through the middle of the A1:Z1 merge, clipped to eight columns.
  // The seven columns the clipping covers to the right emit separators in the
  // TSV but no <td>, because cell_clipboard covers them with the merge.
  ['merge-band', { row0: 0, col0: 11, row1: 0, col1: 18 }, {
    text: 'Long merged' + '\t'.repeat(7),
    html: meta + '<tr><td colspan="8">Long merged</td></tr></table>',
  }],
  // Two rows at the right end of the A1:Z1 merge; only the first has content.
  ['merge-tail', { row0: 0, col0: 24, row1: 1, col1: 25 }, {
    text: 'Long merged\t\n\t',
    html: meta + '<tr><td colspan="2">Long merged</td></tr><tr><td></td><td></td></tr></table>',
  }],
  // Columns B..Z visible (C hidden): the merge covers every visible column,
  // so the clipping emits one colspan="24" cell and no covered cells.
  ['merge-hidden-cross', { row0: 0, col0: 1, row1: 0, col1: 25 }, {
    text: 'Long merged' + '\t'.repeat(23),
    html: meta + '<tr><td colspan="24">Long merged</td></tr></table>',
  }],
  // A single far row inside the B3:B40 merge, four tile rows below its anchor.
  ['merge-deep', { row0: 30, col0: 1, row1: 30, col1: 1 }, {
    text: 'Tall',
    html: meta + '<tr><td>Tall</td></tr></table>',
  }],
  // A band of four rows clipped out of the B3:B40 merge; the three covered
  // rows below anchor emit empty TSV lines and empty <tr> elements.
  ['merge-deep-band', { row0: 11, col0: 1, row1: 14, col1: 1 }, {
    text: 'Tall\n\n\n',
    html: meta + '<tr><td rowspan="4">Tall</td></tr><tr></tr><tr></tr><tr></tr></table>',
  }],
  // Both merges and one plain cell in one grid, with column C skipped.
  ['combined', { row0: 0, col0: 0, row1: 2, col1: 3 }, {
    text: 'Long merged\t\t\n\t\t\n\tTall\t',
    html: meta +
      '<tr><td colspan="3">Long merged</td></tr>' +
      '<tr><td></td><td></td><td></td></tr>' +
      '<tr><td></td><td>Tall</td><td></td></tr></table>',
  }],
  // Plain cells far from every merge anchor.
  ['plain-far', { row0: 9, col0: 13, row1: 9, col1: 13 }, {
    text: 'Plain',
    html: meta + '<tr><td>Plain</td></tr></table>',
  }],
  ['plain-deep', { row0: 39, col0: 4, row1: 39, col1: 4 }, {
    text: 'Edge',
    html: meta + '<tr><td>Edge</td></tr></table>',
  }],
];

const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const browserErrors = [];
  page.on('pageerror', (error) => browserErrors.push(String(error)));
  await page.goto(base + '/merge-test.html', { waitUntil: 'networkidle' });
  const merged = await page.evaluate(async (cases) => {
    const moon = await import('/_build/js/debug/build/browser/browser.js');
    const workerUrl = '/_build/js/debug/build/render_worker/render_worker.js';
    const bytes = async (path) => new Uint8Array(await (await fetch(path)).arrayBuffer());
    const attempt = async (makeSource, range) => {
      const client = moon.bdf_render_worker_client(new Worker(workerUrl, { type: 'module' }));
      try {
        // A buffer source is transferred to the Worker, so every attempt
        // builds a fresh source and every Worker starts from a spotless client.
        const [source, password] = await makeSource();
        await client.open(source, password);
        return { ok: true, value: await client.sheetClipboard('cells', range) };
      } catch (error) {
        return { ok: false, name: error.name, message: error.message };
      } finally {
        client.terminate();
      }
    };
    const sources = {
      buffer: async () => [{ kind: 'buffer', buffer: (await bytes('/compat/sheet/merge.bdf')).buffer }],
      'buffer-encrypted': async () => [
        { kind: 'buffer', buffer: (await bytes('/compat/sheet/merge-encrypted.bdf')).buffer },
        'pass',
      ],
      split: async () => [{ kind: 'split', base: '/compat/sheet/merge-split/' }],
      'split-encrypted': async () => [
        { kind: 'split', base: '/compat/sheet/merge-encrypted-split/' },
        'pass',
      ],
    };
    const out = [];
    for (const [name, range] of cases) {
      for (const [source, makeSource] of Object.entries(sources)) {
        out.push({ name, source, range, result: await attempt(makeSource, range) });
      }
    }
    // A repeated request on one client must return the same answer.
    const client = moon.bdf_render_worker_client(new Worker(workerUrl, { type: 'module' }));
    await client.open({ kind: 'buffer', buffer: (await bytes('/compat/sheet/merge.bdf')).buffer });
    const first = await client.sheetClipboard('cells', { row0: 0, col0: 24, row1: 0, col1: 24 });
    const second = await client.sheetClipboard('cells', { row0: 0, col0: 24, row1: 0, col1: 24 });
    client.terminate();
    out.push({ name: 'repeat', source: 'buffer', result: { ok: JSON.stringify(first) === JSON.stringify(second), value: { first, second } } });
    return out;
  }, cases.map(([name, range]) => [name, range]));

  const failures = [];
  for (const [name, , expected] of cases) {
    for (const source of ['buffer', 'buffer-encrypted', 'split', 'split-encrypted']) {
      const entry = merged.find((item) => item.name === name && item.source === source);
      assert.ok(entry, source + ' result present: ' + name);
      if (!entry.result.ok) {
        failures.push(name + ' (' + source + ') failed: ' + entry.result.message);
        continue;
      }
      const actual = JSON.stringify(entry.result.value);
      try {
        assert.deepEqual(entry.result.value, expected, name + ' (' + source + ')');
      } catch (error) {
        failures.push(String(error.message).split('\n').slice(0, 12).join('\n') + ' [actual ' + actual + ']');
      }
    }
  }
  assert.deepEqual([], failures, 'clipped merge serialization mismatches');
  const repeat = merged.find((entry) => entry.name === 'repeat');
  assert.ok(repeat, 'repeat result present');
  assert.ok(repeat.result.ok, 'repeated sheetClipboard requests agree: ' + JSON.stringify(repeat.result.value));
  assert.deepEqual(browserErrors, [], 'no uncaught page errors');
} finally {
  await browser.close();
  await new Promise((resolve) => server.close(resolve));
}
console.log('merge-clipboard-test: multi-tile merged spans passed for buffer, split and encrypted sources');
