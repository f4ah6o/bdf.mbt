#!/usr/bin/env python3
"""Generate convert/pptx/presets_generated.mbt from the upstream preset table.

The upstream converter stores the DrawingML preset geometry definitions in
converter/internal/ooxml/drawingml/presets.xml.gz. This script reads that file
and writes the MoonBit registry the PowerPoint converter evaluates, so the
formulas and paths can be transcribed without hand copying.

Usage (from the repository root):
  python3 compat/pptx/generate_presets.py
"""

import gzip
import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / ".upstream/converter/internal/ooxml/drawingml/presets.xml.gz"
OUTPUT = ROOT / "convert/pptx/presets_generated.mbt"

COMMANDS = {
    "moveTo": ("PptxMove", ["x", "y"]),
    "lnTo": ("PptxLine", ["x", "y"]),
    "quadBezTo": ("PptxQuad", ["x", "y", "x", "y"]),
    "cubicBezTo": ("PptxCubic", ["x", "y", "x", "y", "x", "y"]),
    "arcTo": ("PptxArc", ["wR", "hR", "stAng", "swAng"]),
    "close": ("PptxClose", []),
}


def quote(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def guide_list(node, child):
    entries = []
    if node is None:
        return entries
    for g in node.findall(child):
        entries.append((g.get("name", ""), g.get("fmla", "")))
    return entries


def number(value):
    value = value.strip()
    if value == "":
        value = "0"
    if "." not in value and "e" not in value.lower():
        value += ".0"
    return value


def main():
    if not SOURCE.exists():
        sys.exit(f"missing {SOURCE}")
    root = ET.fromstring(gzip.open(SOURCE, "rb").read().decode("utf-8"))
    out = []
    out.append("// Generated by compat/pptx/generate_presets.py from upstream")
    out.append("// converter/internal/ooxml/drawingml/presets.xml.gz; do not edit.")
    out.append("")
    out.append("///|")
    out.append("/// The DrawingML preset geometry table: adjust values, guides, text")
    out.append("/// rectangle and path commands, as upstream geometry.go reads it.")
    out.append("let pptx_presets : Map[String, PptxPresetDef] = {")
    for shape in root:
        name = shape.tag
        av = guide_list(shape.find("avLst"), "gd")
        gd = guide_list(shape.find("gdLst"), "gd")
        rect = ("", "", "", "")
        r = shape.find("rect")
        if r is not None:
            rect = (r.get("l", ""), r.get("t", ""), r.get("r", ""), r.get("b", ""))
        out.append("  %s: {" % quote(name))
        out.append("    av: [%s]," % ", ".join(
            "(%s, %s)" % (quote(n), quote(f)) for n, f in av))
        out.append("    gd: [%s]," % ", ".join(
            "(%s, %s)" % (quote(n), quote(f)) for n, f in gd))
        out.append("    rect: (%s, %s, %s, %s)," % tuple(quote(v) for v in rect))
        paths = []
        path_list = shape.find("pathLst")
        if path_list is not None:
            for path in path_list.findall("path"):
                commands = []
                for cmd in path:
                    cname, attrs = COMMANDS[cmd.tag]
                    if cname == "PptxClose":
                        commands.append("PptxClose")
                    elif cname == "PptxArc":
                        commands.append("PptxArc(%s)" % ", ".join(
                            quote(cmd.get(a, "0")) for a in attrs))
                    else:
                        points = cmd.findall("pt")
                        values = []
                        for pt in points:
                            values.append(quote(pt.get("x", "0")))
                            values.append(quote(pt.get("y", "0")))
                        commands.append("%s(%s)" % (cname, ", ".join(values)))
                paths.append(
                    "      { fill: %s, stroke: %s, width: %s, height: %s, commands: [%s], },"
                    % (
                        quote(path.get("fill", "norm")),
                        "true" if path.get("stroke", "true") != "false" else "false",
                        number(path.get("w", "0")),
                        number(path.get("h", "0")),
                        ", ".join(commands),
                    )
                )
        out.append("    paths: [")
        out.extend(paths)
        out.append("    ],")
        out.append("  },")
    out.append("}")
    out.append("")
    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes, {len(list(root))} presets)")


if __name__ == "__main__":
    main()
