// Generate the built-in style data from table-styles.json, which is exported
// by generate-styles_test.go from upstream's ECMA-376 preset styles.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const definitions = JSON.parse(readFileSync(new URL('./table-styles.json', import.meta.url)));
const names = Object.keys(definitions).sort();
const regions = [];
const unique = new Map();
function regionId(region) {
  if (!region) return -1;
  const key = JSON.stringify(region);
  if (!unique.has(key)) { unique.set(key, regions.length); regions.push(region); }
  return unique.get(key);
}
const rows = names.map(name => {
  const d = definitions[name];
  const ids = ['wholeTable', 'firstRowStripe', 'secondRowStripe', 'headerRow'].map(key => regionId(d[key]));
  return `    "${name.toLowerCase().slice('tablestyle'.length)}" => Some({ whole: style_region(${ids[0]}), first: style_region(${ids[1]}), second: style_region(${ids[2]}), header: style_region(${ids[3]}), })`;
});
const weights = { '': 0, thin: 6, medium: 11, double: 12, thick: 13 };
const blocks = regions.map((region, id) => {
  const borders = region.borders.map(border => {
    if (!(border.style in weights)) throw Error('Unknown border: ' + border.style);
    return `{ weight: ${weights[border.style]}, color: ${border.color}U }`;
  }).join(', ');
  return `    ${id} => { fill: ${region.fill}U, color: ${region.fontColor}U, bold: ${region.bold === true}, size: ${region.size}, borders: [${borders}] }`;
});
const source = `// Generated by compat/sheet/generate-style-source.mjs; do not edit.\n\n///|\nfn style_region(index : Int32) -> GridStyleRegion {\n  match index {\n${blocks.join('\n')}\n    _ => { fill: 0U, color: 0U, bold: false, size: 1, borders: [] }\n  }\n}\n\n///|\nfn grid_builtin_style(name : String) -> GridStyle? {\n  let lower = name.replace_all(old="K", new="K").to_lower().replace_all(old="ſ", new="s")\n  let key = if lower.has_prefix("tablestyle") { lower[10:].to_owned() } else { lower }\n  match key {\n${rows.join('\n')}\n    _ => None\n  }\n}\n`;
const formatted = execFileSync('moonfmt', ['-'], { input: source, encoding: 'utf8' });
const output = new URL('../../convert/sheet/table_styles_generated.mbt', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== formatted) throw Error('Generated style source is out of date');
} else writeFileSync(output, formatted);
