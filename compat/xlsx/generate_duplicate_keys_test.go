//go:build ignore

// Copy into upstream converter/xlsx and run TestCodexXLSXDuplicateKeys.
package xlsx

import (
	"bufio"
	"fmt"
	"math"
	"math/rand"
	"os"
	"path/filepath"
	"strconv"
	"testing"
)

func TestCodexXLSXDuplicateKeys(t *testing.T) {
	root := os.Getenv("BDF_FIXTURE_ROOT")
	if root == "" {
		t.Fatal("BDF_FIXTURE_ROOT required")
	}
	f, err := os.Create(filepath.Join(root, "convert/xlsx/conditional_duplicate_generated_wbtest.mbt"))
	if err != nil {
		t.Fatal(err)
	}
	w := bufio.NewWriter(f)
	fmt.Fprintln(w, "///|\n// Generated by compat/xlsx/generate_duplicate_keys_test.go from Go FormatFloat.\ntest \"Go duplicate numeric keys\" {\n  let cases : Array[(UInt64, UInt64, Bool)] = [")
	emit := func(a, b float64) {
		fmt.Fprintf(w, "    (0x%016xUL, 0x%016xUL, %t),\n", math.Float64bits(a), math.Float64bits(b), strconv.FormatFloat(a, 'g', 15, 64) == strconv.FormatFloat(b, 'g', 15, 64))
	}
	emit(0, math.Copysign(0, -1))
	for e := -280; e <= 280; e += 10 {
		x := math.Pow10(e)
		emit(x, math.Nextafter(x, 0))
		emit(x, math.Nextafter(x, math.Inf(1)))
	}
	r := rand.New(rand.NewSource(209321))
	for i := 0; i < 1024; i++ {
		exponent := r.Intn(561) - 280
		a := (0.1 + r.Float64()*0.9) * math.Pow10(exponent)
		if i%2 != 0 {
			a = -a
		}
		b := a
		for j := 0; j <= i%7; j++ {
			b = math.Nextafter(b, math.Inf(1))
		}
		emit(a, b)
	}
	fmt.Fprintln(w, `  ]
  for (a, b, equal) in cases {
    let left : XlsxCell = { column: 0, style: 0, kind: 1, number: a.reinterpret_as_double(), text: "" }
    let right : XlsxCell = { column: 0, style: 0, kind: 1, number: b.reinterpret_as_double(), text: "" }
    assert_eq(xlsx_conditional_duplicate_key(left) == xlsx_conditional_duplicate_key(right), equal)
  }
}`)
	if err := w.Flush(); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
}
