//go:build ignore

// Copy into upstream converter/xlsx and run TestCodexXLSXLowercaseTable.
package xlsx

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"testing"
	"unicode"
)

func TestCodexXLSXLowercaseTable(t *testing.T) {
	root := os.Getenv("BDF_FIXTURE_ROOT")
	if root == "" {
		t.Fatal("BDF_FIXTURE_ROOT required")
	}
	f, err := os.Create(filepath.Join(root, "convert/xlsx/go_lowercase_generated.mbt"))
	if err != nil {
		t.Fatal(err)
	}
	w := bufio.NewWriter(f)
	fmt.Fprintf(w, "///|\n// Generated by compat/xlsx/generate_lowercase_test.go from Go Unicode %s.\nlet xlsx_go_lowercase : Array[(Int32, Int32)] = [\n", unicode.Version)
	for c := rune(0); c <= unicode.MaxRune; c++ {
		if lower := unicode.ToLower(c); lower != c {
			fmt.Fprintf(w, "  (0x%x, 0x%x),\n", c, lower)
		}
	}
	fmt.Fprintln(w, "]")
	if err := w.Flush(); err != nil {
		t.Fatal(err)
	}
	if err := f.Close(); err != nil {
		t.Fatal(err)
	}
}
