// Emit a browser-resolvable downstream plugin Worker from the bdf.mbt
// package that ships this script. This is the documented deployment path
// for adding a format next to the shipped builtins:
//
//   cp -R node_modules/bdf.mbt/dist ./public/bdf.mbt-dist/
//   node node_modules/bdf.mbt/dist/tools/emit-downstream-worker.mjs \
//     --plugin ./src/my-plugin.mjs \
//     --out   ./public/my-plugin-worker.mjs \
//     --prefix /bdf.mbt-dist
//
// Why this exists: a served Worker file cannot import bare npm specifiers,
// and `new Worker()` fetches a URL. The emitted worker therefore imports
// every package entry by its served URL under --prefix, and imports the
// consumer's own plugin module by a URL relative to the emitted file. Both
// files must be inside the served tree (the emitter refuses a plugin module
// outside the emitted worker's deployment directory, because the browser
// could not fetch it). The plugin descriptor is validated at emit time with
// the package's own validator, so a malformed plugin fails the build step
// instead of the first conversion. The emitter itself only reads the
// package and the plugin module, and writes exactly the --out file.

import { existsSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = ResolveDistRoot(dirname(fileURLToPath(import.meta.url)));

function ResolveDistRoot(toolsDirectory) {
  const distRoot = resolve(toolsDirectory, "..");
  if (!existsSync(resolve(distRoot, "plugin", "worker.js"))) {
    throw new Error(
      "run the emitter that ships inside the bdf.mbt tarball " +
        "(node_modules/bdf.mbt/dist/tools/emit-downstream-worker.mjs); " +
        "this copy is not inside a served package dist tree",
    );
  }
  return distRoot;
}

function argument(name) {
  const at = process.argv.indexOf(name);
  if (at === -1 || at + 1 >= process.argv.length || process.argv[at + 1].startsWith("--")) {
    throw new Error(`missing argument ${name} (try --help for the documented invocation)`);
  }
  return process.argv[at + 1];
}

function validatePrefix(prefix) {
  if (!prefix.startsWith("/") || prefix.includes("..") || prefix.includes("\\")
    || prefix.includes("//") || /[?#]/.test(prefix)) {
    throw new Error(`--prefix must be an absolute URL path into the served tree, like /bdf.mbt-dist, not "${prefix}"`);
  }
  return prefix;
}

function servedUrl(prefix, packageFile) {
  const suffix = relative(packageDirectory, resolve(packageFile)).split("\\").join("/");
  if (suffix.startsWith("..") || isAbsolute(suffix)) {
    throw new Error(`the package file ${packageFile} is not inside the dist tree`);
  }
  return `${prefix}/${suffix}`;
}

function pluginSpecifier(outFile, pluginFile) {
  const relativeName = relative(dirname(resolve(outFile)), resolve(pluginFile)).split("\\").join("/");
  if (relativeName.startsWith("..")) {
    throw new Error(
      `the plugin module ${pluginFile} must live next to the emitted worker ${outFile} ` +
        "(inside the served tree), because the emitted Worker imports it by relative URL",
    );
  }
  return relativeName.startsWith("./") || relativeName.startsWith("../") ? relativeName : `./${relativeName}`;
}

async function main() {
  const pluginFile = argument("--plugin");
  const outFile = argument("--out");
  const prefix = validatePrefix(argument("--prefix"));
  if (!existsSync(pluginFile)) {
    throw new Error(`the plugin module does not exist: ${pluginFile}`);
  }
  // every served URL names a file that actually ships in the package
  const entries = {
    worker: servedUrl(prefix, resolve(packageDirectory, "plugin", "worker.js")),
    adapter: servedUrl(prefix, resolve(packageDirectory, "plugin", "adapters", "docuworks.js")),
    api: servedUrl(prefix, resolve(packageDirectory, "plugin", "index.js")),
    xdw: servedUrl(prefix, resolve(packageDirectory, "xdw", "docuworks_js.js")),
  };
  for (const url of Object.values(entries)) {
    const local = resolve(packageDirectory, url.slice(prefix.length + 1));
    if (!existsSync(local)) {
      throw new Error(`the package layout is missing ${local} for served URL ${url}`);
    }
  }
  // validate the consumer's plugin before emitting, with the shipped validator
  const { defineFormatPlugin } = await import(`file://${resolve(packageDirectory, "plugin", "index.js")}`);
  const pluginModule = await import(`file://${resolve(pluginFile)}`);
  const descriptor = pluginModule.plugin ?? pluginModule.default;
  defineFormatPlugin(descriptor);
  const userImport = pluginSpecifier(outFile, pluginFile);
  const worker = [
    "// Generated by bdf.mbt's emit-downstream-worker tool; regenerate it",
    "// whenever the plugin module or the package update. Imports are served",
    "// URLs, because a Worker file cannot use bare npm specifiers.",
    `import { installPluginConverterWorker } from "${entries.worker}";`,
    `import { docuworksPlugin } from "${entries.adapter}";`,
    `import { moonbitDocuWorks } from "${entries.api}";`,
    `import * as xdw from "${entries.xdw}";`,
    `import * as user from "${userImport}";`,
    "const plugin = user.plugin ?? user.default;",
    "installPluginConverterWorker([plugin, docuworksPlugin({ delegate: moonbitDocuWorks(xdw) })]);",
    "",
  ].join("\n");
  writeFileSync(resolve(outFile), worker);
  console.log(`emitted ${resolve(outFile)} (served package prefix ${prefix})`);
}

await main();
